import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { validId, validateValues, validateRelations } from "./validation.mjs";
const {resources:r}=JSON.parse(readFileSync(new URL("./crm-config.json",import.meta.url),"utf8"));
const uuid="b6f3ba53-7e32-4a13-9d03-6a9d4e8381ba";
const values=(n,v,c=false)=>validateValues(n,r[n],v,c);
test("UUID válido",()=>assert.equal(validId("candidates",uuid),uuid));
test("UUID inválido rechazado",()=>assert.throws(()=>validId("candidates","bad")));
test("ID booleano de ajustes",()=>assert.equal(validId("settings","true"),true));
test("Ajustes no singleton rechazados",()=>assert.throws(()=>validId("settings","false")));
test("Alta mínima de candidato",()=>assert.deepEqual(values("candidates",{first_name:" Prueba ",last_name:"Admin"},true),{first_name:"Prueba",last_name:"Admin"}));
test("Nombre obligatorio",()=>assert.throws(()=>values("candidates",{last_name:"Admin"},true)));
test("Nombre vacío rechazado",()=>assert.throws(()=>values("candidates",{first_name:" "},false)));
test("No acepta referencia manipulada",()=>assert.throws(()=>values("candidates",{reference:"MUK-1"},false)));
test("No acepta rol manipulado",()=>assert.throws(()=>values("staff",{role:"admin"},false)));
test("No acepta created_by del navegador",()=>assert.throws(()=>values("notes",{body:"Nota",created_by:uuid},true)));
test("Teléfono válido",()=>assert.equal(values("candidates",{phone_e164:"+212600000000"}).phone_e164,"+212600000000"));
test("Teléfono mal formado",()=>assert.throws(()=>values("candidates",{phone_e164:"600 00"})));
test("Correo mal formado",()=>assert.throws(()=>values("candidates",{email:"incorrecto"})));
test("Email opcional borrable",()=>assert.equal(values("candidates",{email:null}).email,null));
test("Estado inválido",()=>assert.throws(()=>values("candidates",{status:"inventado"})));
test("Fecha exige zona",()=>assert.throws(()=>values("candidates",{next_action_at:"2026-10-25T10:00"})));
test("Fecha ISO aceptada",()=>assert.equal(values("candidates",{next_action_at:"2026-10-25T10:00:00Z"}).next_action_at,"2026-10-25T10:00:00Z"));
test("Presupuesto sin moneda",()=>assert.throws(()=>validateRelations("candidates",{budget_amount:100})));
test("Presupuesto negativo",()=>assert.throws(()=>values("candidates",{budget_amount:-1})));
test("Nota demasiado larga",()=>assert.throws(()=>values("notes",{body:"x".repeat(20001)},true)));
test("Estudios en curso no tienen fin",()=>assert.throws(()=>validateRelations("education",{is_current:true,end_date:"2026-01-01"})));
test("Estudios: orden de fechas",()=>assert.throws(()=>validateRelations("education",{start_date:"2026-02-01",end_date:"2026-01-01"})));
test("Bloqueo: orden de horas",()=>assert.throws(()=>validateRelations("blocks",{starts_at:"2026-10-25T10:00:00Z",ends_at:"2026-10-25T09:00:00Z"})));
test("Horario: cierre posterior",()=>assert.throws(()=>validateRelations("settings",{opening_time:"18:00",closing_time:"10:00"})));
test("Nombre de empleado limitado",()=>assert.throws(()=>values("staff",{full_name:"x".repeat(201)})));
test("No acepta cuerpo array",()=>assert.throws(()=>values("candidates",[])));
test("Sin cambios rechazado",()=>assert.throws(()=>values("candidates",{})));
